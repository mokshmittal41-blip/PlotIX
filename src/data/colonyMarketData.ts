// Helper: Calculate distance in KM using Haversine formula
function getDistanceFromLatLonInKm(lat1: number, lon1: number, lat2: number, lon2: number): number {
  const R = 6371; // Radius of earth in km
  const dLat = (lat2 - lat1) * (Math.PI / 180);
  const dLon = (lon2 - lon1) * (Math.PI / 180);
  const a =
    Math.sin(dLat / 2) * Math.sin(dLat / 2) +
    Math.cos(lat1 * (Math.PI / 180)) * Math.cos(lat2 * (Math.PI / 180)) * Math.sin(dLon / 2) * Math.sin(dLon / 2);
  const c = 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
  return R * c;
}

// Find nearest City Hub for user's GPS coords
export function findNearestCityHub(lat: number, lng: number): CityMarketHub {
  let closestHub = CITY_MARKET_HUBS[0];
  let minDistance = Infinity;

  for (const hub of CITY_MARKET_HUBS) {
    const dist = getDistanceFromLatLonInKm(lat, lng, hub.centerCoords[0], hub.centerCoords[1]);
    if (dist < minDistance) {
      minDistance = dist;
      closestHub = hub;
    }
  }

  return closestHub;
}
